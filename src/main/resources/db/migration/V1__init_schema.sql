-- V1: początkowy schemat Job Trackera
-- Enumy trzymamy jako VARCHAR + CHECK (mapowanie @Enumerated(EnumType.STRING)).
-- Dodanie nowej wartości enuma = nowa migracja zmieniająca CHECK.
-- created_at / updated_at wypełnia JPA Auditing (updated_at nie ma triggera).

-- ---------------------------------------------------------------- company
CREATE TABLE company (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    industry   VARCHAR(255),
    website    VARCHAR(500),
    notes      TEXT,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_company_name ON company (lower(name));

-- -------------------------------------------------------- company_overview
-- Wiele wpisów na firmę (historia regeneracji); "aktualny" = najnowszy generated_at.
CREATE TABLE company_overview (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT       NOT NULL REFERENCES company (id) ON DELETE CASCADE,
    overview_text TEXT         NOT NULL,
    source_text   TEXT,
    generated_at  TIMESTAMPTZ  NOT NULL,
    model_used    VARCHAR(100),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_company_overview_company ON company_overview (company_id, generated_at DESC);

-- ----------------------------------------------------------------- contact
CREATE TABLE contact (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   BIGINT       NOT NULL REFERENCES company (id) ON DELETE CASCADE,
    first_name   VARCHAR(100) NOT NULL,
    last_name    VARCHAR(100),
    position     VARCHAR(255),
    email        VARCHAR(255),
    phone        VARCHAR(50),
    linkedin_url VARCHAR(500),
    notes        TEXT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_contact_company ON contact (company_id);

-- ------------------------------------------------------------ job_application
CREATE TABLE job_application (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT       NOT NULL REFERENCES company (id),
    position        VARCHAR(255) NOT NULL,
    offer_url       VARCHAR(1000),
    source          VARCHAR(30)  NOT NULL DEFAULT 'OTHER',
    location        VARCHAR(255),
    work_mode       VARCHAR(20),
    employment_type VARCHAR(20),
    seniority_level VARCHAR(20),

    -- SalaryRange (@Embeddable), wszystko opcjonalne
    salary_min      NUMERIC(12, 2),
    salary_max      NUMERIC(12, 2),
    salary_currency VARCHAR(3),
    salary_period   VARCHAR(10),
    salary_basis    VARCHAR(10),

    raw_description TEXT,
    deadline        DATE,
    date_found      DATE         NOT NULL DEFAULT CURRENT_DATE,
    date_applied    DATE,
    current_status  VARCHAR(30)  NOT NULL DEFAULT 'FOUND',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_job_application_source CHECK (source IN
        ('PRACUJ_PL', 'LINKEDIN', 'THE_PROTOCOL', 'OTHER')),
    CONSTRAINT ck_job_application_work_mode CHECK (work_mode IS NULL OR work_mode IN
        ('ONSITE', 'HYBRID', 'REMOTE')),
    CONSTRAINT ck_job_application_employment_type CHECK (employment_type IS NULL OR employment_type IN
        ('UOP', 'B2B', 'ZLECENIE', 'INNE')),
    CONSTRAINT ck_job_application_seniority CHECK (seniority_level IS NULL OR seniority_level IN
        ('INTERN', 'JUNIOR', 'MID', 'SENIOR')),
    CONSTRAINT ck_job_application_salary_period CHECK (salary_period IS NULL OR salary_period IN
        ('MONTH', 'HOUR')),
    CONSTRAINT ck_job_application_salary_basis CHECK (salary_basis IS NULL OR salary_basis IN
        ('GROSS', 'NET')),
    CONSTRAINT ck_job_application_salary_range CHECK
        (salary_min IS NULL OR salary_max IS NULL OR salary_min <= salary_max),
    CONSTRAINT ck_job_application_status CHECK (current_status IN
        ('FOUND', 'APPLIED', 'HR_SCREEN', 'TECH_TASK', 'TECH_INTERVIEW', 'FINAL_INTERVIEW',
         'OFFER_RECEIVED', 'ACCEPTED', 'REJECTED', 'WITHDRAWN', 'GHOSTED'))
);

CREATE INDEX idx_job_application_company ON job_application (company_id);
CREATE INDEX idx_job_application_status  ON job_application (current_status);
CREATE INDEX idx_job_application_deadline ON job_application (deadline);

-- ----------------------------------------------------------- status_history
CREATE TABLE status_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL REFERENCES job_application (id) ON DELETE CASCADE,
    status         VARCHAR(30) NOT NULL,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    note           TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_status_history_status CHECK (status IN
        ('FOUND', 'APPLIED', 'HR_SCREEN', 'TECH_TASK', 'TECH_INTERVIEW', 'FINAL_INTERVIEW',
         'OFFER_RECEIVED', 'ACCEPTED', 'REJECTED', 'WITHDRAWN', 'GHOSTED'))
);

CREATE INDEX idx_status_history_application ON status_history (application_id, changed_at);

-- StatusHistory N:N Contact (kto brał udział w danym etapie)
CREATE TABLE status_history_contact (
    status_history_id BIGINT NOT NULL REFERENCES status_history (id) ON DELETE CASCADE,
    contact_id        BIGINT NOT NULL REFERENCES contact (id) ON DELETE CASCADE,
    PRIMARY KEY (status_history_id, contact_id)
);

CREATE INDEX idx_status_history_contact_contact ON status_history_contact (contact_id);

-- ---------------------------------------------------------------- document
-- Na razie tylko metadane; kolumny pod upload pliku dojdą kolejną migracją.
CREATE TABLE document (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL,
    name        VARCHAR(255) NOT NULL,
    upload_date DATE         NOT NULL DEFAULT CURRENT_DATE,
    archived    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_document_type CHECK (type IN ('CV', 'COVER_LETTER', 'OTHER'))
);

-- JobApplication N:N Document
CREATE TABLE application_document (
    application_id BIGINT NOT NULL REFERENCES job_application (id) ON DELETE CASCADE,
    document_id    BIGINT NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    PRIMARY KEY (application_id, document_id)
);

CREATE INDEX idx_application_document_document ON application_document (document_id);

-- ------------------------------------------------------------ offer_summary
-- Wiele wpisów na aplikację; "aktualne" streszczenie = najnowszy generated_at.
CREATE TABLE offer_summary (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL REFERENCES job_application (id) ON DELETE CASCADE,
    summary_text   TEXT        NOT NULL,
    generated_at   TIMESTAMPTZ NOT NULL,
    model_used     VARCHAR(100),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_offer_summary_application ON offer_summary (application_id, generated_at DESC);
